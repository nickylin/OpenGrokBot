import { execFile } from "node:child_process";
import { existsSync } from "node:fs";
import { mkdir, stat, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { join } from "node:path";
import { promisify } from "node:util";
import { homeDir } from "./paths.js";
import type { McpServerConfig, Settings } from "./types.js";

/**
 * Browser control, two layers:
 *
 * 1. MCP presets — one-click mcp.json entries for Microsoft's Playwright
 *    MCP or Google's Chrome DevTools MCP. No engine code here; the v0.4
 *    MCP client does the work.
 *
 * 2. Linked browser apps — the user can explicitly link a local browser
 *    CLI (ego lite, or the open-source agent-browser) in Settings →
 *    Browser. Bots then get native browser_* tools, each translated to
 *    one CLI invocation and run through the same localExec approval gate
 *    as run_shell. Nothing is linked by default; detection alone never
 *    enables anything.
 */

export type BrowserProvider = "ego" | "agent-browser";
export type BrowserAction = "open" | "snapshot" | "click" | "fill" | "screenshot";

const execFileAsync = promisify(execFile);

const BIN_NAME: Record<BrowserProvider, string> = {
  ego: "ego-browser",
  "agent-browser": "agent-browser",
};

const WELL_KNOWN_PATHS: Record<BrowserProvider, string[]> = {
  ego: [join(homedir(), ".local", "bin", "ego-browser")],
  "agent-browser": [join(homedir(), ".local", "bin", "agent-browser")],
};

export async function detectProvider(provider: BrowserProvider): Promise<string | null> {
  for (const p of WELL_KNOWN_PATHS[provider]) {
    if (existsSync(p)) return p;
  }
  try {
    const { stdout } = await execFileAsync("which", [BIN_NAME[provider]]);
    const p = stdout.trim().split("\n")[0];
    if (p) return p;
  } catch {
    /* not on PATH */
  }
  return null;
}

export function browserDir(): string {
  return join(homeDir(), "browser");
}

export function screenshotPath(): string {
  return join(browserDir(), "last-screenshot.png");
}

export async function screenshotInfo(): Promise<{ exists: boolean; updatedAt: string | null }> {
  try {
    const st = await stat(screenshotPath());
    return { exists: true, updatedAt: st.mtime.toISOString() };
  } catch {
    return { exists: false, updatedAt: null };
  }
}

export function linkedProvider(settings: Settings): BrowserProvider | null {
  const link = settings.browserLink;
  if (link?.enabled && (link.provider === "ego" || link.provider === "agent-browser")) {
    return link.provider;
  }
  return null;
}

export type Invocation = { command: string; args: string[] };

/**
 * ego lite is driven by JavaScript against its page SDK (taskSpace /
 * page.goto / page.snapshot / page.click / page.fill), executed by the
 * ego-browser binary's embedded Node runtime. This adapter is written
 * against Citro Labs' public documentation; the agent-browser adapter
 * below is the one covered by live tests, and the ego path reports its
 * errors verbatim so a mismatched ego version is visible, not silent.
 */
function egoScript(action: BrowserAction, input: { url?: string; selector?: string; text?: string }): string {
  const lit = (v: string) => JSON.stringify(v);
  const shot = screenshotPath();
  const body = (() => {
    switch (action) {
      case "open":
        return `await page.goto(${lit(input.url ?? "")});\n  console.log(await page.snapshot());`;
      case "snapshot":
        return `console.log(await page.snapshot());`;
      case "click":
        return `await page.click(${lit(input.selector ?? "")});\n  console.log(await page.snapshot());`;
      case "fill":
        return `if (typeof page.fill === "function") await page.fill(${lit(input.selector ?? "")}, ${lit(input.text ?? "")});\n  else if (typeof page.type === "function") await page.type(${lit(input.selector ?? "")}, ${lit(input.text ?? "")});\n  else throw new Error("ego page SDK has no fill/type in this version");\n  console.log(await page.snapshot());`;
      case "screenshot":
        return `if (typeof page.screenshot === "function") await page.screenshot({ path: ${lit(shot)} });\n  else if (typeof page.capture === "function") await page.capture(${lit(shot)});\n  else throw new Error("ego page SDK has no screenshot/capture in this version");\n  console.log("screenshot saved");`;
    }
  })();
  return [
    "// Generated by OpenGrokBot to drive ego lite. Do not edit; regenerated per action.",
    "const space = await taskSpace(\"opengrokbot\");",
    "const page = space.page ?? space;",
    "try {",
    `  ${body}`,
    "} catch (err) {",
    "  console.error(err && err.message ? err.message : String(err));",
    "  process.exit(1);",
    "}",
    "",
  ].join("\n");
}

export async function buildInvocation(
  provider: BrowserProvider,
  action: BrowserAction,
  input: { url?: string; selector?: string; text?: string },
): Promise<Invocation> {
  const bin = (await detectProvider(provider)) ?? BIN_NAME[provider];
  await mkdir(browserDir(), { recursive: true });
  if (provider === "agent-browser") {
    switch (action) {
      case "open":
        return { command: bin, args: ["open", input.url ?? ""] };
      case "snapshot":
        return { command: bin, args: ["snapshot"] };
      case "click":
        return { command: bin, args: ["click", input.selector ?? ""] };
      case "fill":
        return { command: bin, args: ["fill", input.selector ?? "", input.text ?? ""] };
      case "screenshot":
        return { command: bin, args: ["screenshot", screenshotPath()] };
    }
  }
  const file = join(browserDir(), "ego-action.mjs");
  await writeFile(file, egoScript(action, input), "utf8");
  return { command: bin, args: ["nodejs", file] };
}

/**
 * Playwright MCP needs its Chrome-for-Testing build downloaded once
 * (~150 MB). Check the Playwright cache first; install only when missing.
 * Returns a human-readable note either way — a failed install must not
 * block adding the preset, since the MCP server's own error message
 * tells the user the same command.
 */
export async function ensurePlaywrightBrowser(): Promise<string> {
  // The exact browser build is pinned by the @playwright/mcp version, so
  // a cache-dir guess can be wrong (an older build may sit there). The
  // install command is idempotent and quick when the right build exists.
  try {
    await execFileAsync("npx", ["-y", "@playwright/mcp@latest", "install-browser", "chrome-for-testing"], {
      timeout: 300_000,
      maxBuffer: 1_000_000,
    });
    return "Playwright browser installed";
  } catch (err) {
    return `Playwright browser install did not finish (${err instanceof Error ? err.message.split("\n")[0] : String(err)}). Run it manually: npx @playwright/mcp@latest install-browser chrome-for-testing`;
  }
}

export function browserPreset(kind: "playwright" | "devtools"): McpServerConfig {
  if (kind === "playwright") {
    return {
      name: "playwright",
      command: "npx",
      // --browser chromium uses Playwright's own Chrome-for-Testing build,
      // so no system Chrome install is required.
      args: [
        "-y",
        "@playwright/mcp@latest",
        "--browser",
        "chromium",
        "--user-data-dir",
        join(homeDir(), "browser-profile"),
      ],
      enabled: true,
    };
  }
  return {
    name: "devtools",
    command: "npx",
    args: ["-y", "chrome-devtools-mcp@latest", "--no-usage-statistics"],
    enabled: true,
  };
}
